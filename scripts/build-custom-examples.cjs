// One source for each custom example: execute it in the gallery and show it in the modal.
const fs = require('node:fs');
const path = require('node:path');
const {highlightCode} = require('./code-format.cjs');
const root = path.resolve(__dirname, '..');
const examples = JSON.parse(fs.readFileSync(path.join(root, 'docs/custom-examples.json')));
const info = Object.fromEntries(Object.entries(examples).map(([id, example]) => [id, {
  description: example.description,
  html: '<button class="copy" type="button">Copy</button>' + highlightCode(example.code, 'javascript', [[1, 5]])
}]));
const source = '// Generated by npm run docs:highlight from docs/custom-examples.json.\n' +
  'const customExampleInfo = ' + JSON.stringify(info, null, 2) + ';\n' +
  Object.values(examples).map(example => '{\n' + example.code + '\n}').join('\n');
fs.writeFileSync(path.join(root, 'docs/custom-examples.js'), source + '\n');
