// The same source powers the gallery and the playground presets.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const examples = {
  ...JSON.parse(fs.readFileSync(path.join(root, 'docs/custom-examples.json'))),
  ...JSON.parse(fs.readFileSync(path.join(root, 'docs/feature-examples.json')))
};
const source = '// Generated by npm run docs:highlight from docs/custom-examples.json.\n' +
  Object.values(examples).map(example => '{\n' + example.code + '\n}').join('\n');
fs.writeFileSync(path.join(root, 'docs/custom-examples.js'), source + '\n');
