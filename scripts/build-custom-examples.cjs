// The same source powers the gallery and the playground presets.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const examples = {
  ...JSON.parse(fs.readFileSync(path.join(root, 'docs/custom-examples.json'))),
  ...JSON.parse(fs.readFileSync(path.join(root, 'docs/feature-examples.json')))
};
const source = '// Generated by npm run docs:highlight from docs/custom-examples.json.\n' +
  Object.values(examples).map(example => '{\n' + example.code + '\n}').join('\n');
fs.writeFileSync(path.join(root, 'docs/custom-examples.js'), source + '\n');

// Keep the basic gallery examples in sync with the guide and playground as well.
const snippets = JSON.parse(fs.readFileSync(path.join(root, 'docs/snippets.json')));
const basicExamples = [
    ['line','lines'], ['bar','bars'], ['custom','custom'],
    ['animation','animation'], ['dates','dates']
];
let gallery = `// Generated from docs/snippets.json by npm run docs:highlight.
for (const plot of document.querySelectorAll('.gallery easy-canvas')) {
    plot.debug = false;
    plot.setAttribute('framerate', '12');
}
document.querySelector('#gallery-bars').setAttribute('controls', 'false');
`;
for (const [key, id] of basicExamples) {
    let code = snippets[key].replaceAll('#' + id, '#gallery-' + id);
    if (key === 'animation') code = code.replace('const t = performance.now() / 1000;',
        "const t = matchMedia('(prefers-reduced-motion: reduce)').matches ? 0 : performance.now() / 1000;");
    gallery += '\n{\n' + code + '\n}\n';
}
gallery += `
const guideSections = ['automatic-layout','features','themes','controls','start','line-plots','bar-plots','linked','custom-drawing','animation-updates','time-axes','typescript','reference','notes'];
if (guideSections.includes(location.hash.slice(1))) location.replace('guide.html' + location.hash);
`;
fs.writeFileSync(path.join(root, 'docs/gallery.js'), gallery);
